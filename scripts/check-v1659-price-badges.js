const assert = require('assert');
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
const read = (p) => fs.readFileSync(path.join(root,p),'utf8');
const pkg = require(path.join(root,'package.json'));
const css = read('public/css/completion-fixes.css');
const card = read('src/views/partials/listing-card.ejs');
let passed=0;
function check(name, fn){ try{ fn(); console.log('✓ '+name); passed++; }catch(e){ console.error('✗ '+name+' — '+e.message); process.exitCode=1; }}
check('release is v1.6.60',()=>assert.strictEqual(pkg.version,'1.6.60'));
check('From remains rendered',()=>assert(card.includes('pricePrefix">From')));
check('currency remains rendered',()=>assert(card.includes('priceCurrency')));
check('price amount remains rendered',()=>assert(card.includes('priceAmount')));
check('Cheapest route fare remains rendered',()=>assert(card.includes('Cheapest route fare')));
check('bus prefix and currency are reduced',()=>assert(css.includes('font-size:.72em!important')));
check('bus amount uses strong 900 weight',()=>assert(css.includes('font-weight:900!important')));
check('fare hint is reduced',()=>assert(css.includes('font-size:9px!important') && css.includes('font-weight:600!important')));
check('image badges are increased slightly',()=>assert(css.includes('font-size:9.5px!important') && css.includes('min-height:22px!important')));
check('inventory badge is increased slightly',()=>assert(css.includes('font-size:9.75px!important')));
check('service worker is cache-busted',()=>assert(read('public/sw.js').includes('classic-trip-static-v1.6.60')));
if(!process.exitCode) console.log(`\n${passed}/11 v1.6.60 price/badge checks passed.`);

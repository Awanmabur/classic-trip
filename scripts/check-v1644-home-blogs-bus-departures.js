'use strict';

const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8');
const pkg = require('../package.json');

const seed = read('scripts/seed-launch-seo-operators.js');
const seedMedia = read('src/utils/seedMedia.js');
const catalog = read('src/services/marketplace/catalogService.js');
const home = read('src/views/pages/home.ejs');
const css = read('public/css/pages/home.css');
const requiredImages = [
  'public/images/blogs/bus-seat-booking.webp',
  'public/images/operators/bebeto-coach.webp',
  'public/images/operators/trinity-express.webp',
  'public/images/operators/zawadi-travel-service.jpg',
  'public/images/operators/eco-bus.webp',
  'public/images/operators/friendship-bus.png',
  'public/images/operators/yy-coaches.webp',
];

const checks = [];
const check = (name, ok) => checks.push([name, Boolean(ok)]);

check('release is v1.6.44 or newer', /^1\.6\.(?:4[4-9]|[5-9]\d|\d{3,})$/.test(pkg.version));
check('homepage loads exactly three published blog cards', catalog.includes("slice(0, 3)") && !catalog.includes("slice(0, 7)"));
check('home blog design is preserved', home.includes('class="blogHomeGrid" id="blogCards"') && css.includes('.blogHomeGrid .blogCard'));
check('bottom-right More blogs button opens the full directory', home.includes('class="moreRow"') && home.includes('href="/blogs"') && css.includes('.moreRow{display:flex;justify-content:flex-end'));
check('approved home stylesheet stays byte-compatible with the v1.6.43 reference', !css.includes('v1.6.44 — keep the designed three-card home blog section'));
check('seed no longer assigns the Classic Trip logo as blog artwork', !seed.includes("image: '/images/launch-lockup-512.png'") && seed.includes('BLOG_IMAGES'));
check('all seven seeded articles have meaningful image mappings', (seedMedia.match(/'[^']+': '\/images\/blogs\//g) || []).length >= 7);
check('all six operator real-bus image files exist', requiredImages.every((file) => fs.existsSync(path.join(root, file))));
check('operator listings receive real bus media', seed.includes('media: seededMedia(OPERATOR_IMAGES[operator.key]') && seed.includes('realBusImage: OPERATOR_IMAGES[operator.key]'));
check('seeded vehicle has a published seat-map backing through bus setup service', seed.includes('busSetupService.createVehicle') && seed.includes("layoutName: '2x2'") && seed.includes('totalSeats: 40'));
check('route stops and route segments are persisted before departure creation', seed.includes('ensureRouteInfrastructure') && seed.includes('RouteStop.findOneAndUpdate') && seed.includes('RouteSegment.create'));
check('researched fares are persisted as fare products and segment fares', seed.includes('FareProduct.create') && seed.includes('BusSegmentFare.create'));
check('departures are generated by the full bus departure service', seed.includes('busDepartureService.createSchedule') && seed.includes('ensureReviewDeparture'));
check('seeded departures stay draft and explicitly require review', seed.includes("status: 'draft'") && seed.includes('operatorConfirmationRequired: true') && seed.includes('Review draft: confirm the exact date/time'));
check('departure seed is future/idempotent rather than duplicate-on-every-run', seed.includes("departAt: { $gt: new Date() }") && seed.includes('notes: marker'));
check('compliance is still not fabricated', seed.includes("complianceProfile: { status: 'not_submitted'") && seed.includes('operatorPermitRef') === false);

const failed = checks.filter(([, ok]) => !ok);
checks.forEach(([name, ok]) => console.log(`${ok ? 'PASS' : 'FAIL'}: ${name}`));
if (failed.length) {
  console.error(`v1.6.44 checks failed (${checks.length - failed.length}/${checks.length}).`);
  process.exit(1);
}
console.log(`v1.6.44 checks passed (${checks.length}/${checks.length}).`);

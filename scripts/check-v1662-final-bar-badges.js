'use strict';
const fs=require('fs'); const path=require('path'); const assert=require('assert');
const root=path.resolve(__dirname,'..'); let passed=0;
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const check=(n,f)=>{try{f(); console.log('✓ '+n); passed++;}catch(e){console.error('✗ '+n+' — '+e.message); process.exitCode=1;}};
const pkg=require(path.join(root,'package.json'));
const css=read('public/css/completion-fixes.css');
const start=css.indexOf('/* v1.6.62 — final desktop bar badge sizing.');
const desktopBlock=css.slice(start);
check('release is v1.6.62',()=>assert.strictEqual(pkg.version,'1.6.62'));
check('v1.6.62 desktop rule exists',()=>assert(start>=0));
check('desktop bar photo badges are larger',()=>assert(desktopBlock.includes('min-height:25px!important')&&desktopBlock.includes('font-size:10.75px!important')));
check('desktop bar departure badge is larger',()=>assert(desktopBlock.includes('max-width:102px!important')&&desktopBlock.includes('padding:5px 8.5px!important')&&desktopBlock.includes('font-size:10.75px!important')));
check('desktop title reserves room for departure badge',()=>assert(desktopBlock.includes('padding-right:98px!important')));
check('change is desktop-only',()=>assert(desktopBlock.includes('@media(min-width:681px)')&&!desktopBlock.includes('@media(max-width:680px)')));
check('service worker is cache-busted',()=>assert(read('public/sw.js').includes('classic-trip-static-v1.6.62')));
if(!process.exitCode) console.log(`\n${passed}/7 v1.6.62 final bar badge checks passed.`);

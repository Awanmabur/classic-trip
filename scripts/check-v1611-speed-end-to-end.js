const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8');
let passed = 0;
function check(label, condition) {
  if (!condition) throw new Error(`FAIL: ${label}`);
  passed += 1;
  console.log(`PASS: ${label}`);
}
const pkg = JSON.parse(read('package.json'));
const app = read('src/app.js');
const csrf = read('src/middlewares/csrf.js');
const flash = read('src/middlewares/flash.js');
const publicPerf = read('src/middlewares/publicPerformance.js');
const catalog = read('src/services/marketplace/catalogService.js');
const css = read('public/css/completion-fixes.css');
const workspace = read('src/views/dashboards/shared/workspace.ejs');
const sw = read('public/sw.js');
check('v1.6.11 speed baseline remains in later releases', pkg.version === '1.6.15' && sw.includes(`classic-trip-static-v${pkg.version}`));
check('production EJS view cache is enabled', app.includes("app.set('view cache', env.isProduction)"));
check('compression has an explicit practical threshold', app.includes('compression({ threshold: 1024, level: 6 })'));
check('public market configuration is reused', app.includes('const PUBLIC_MARKETS = publicMarkets()') && app.includes('res.locals.countryMarkets = PUBLIC_MARKETS'));
check('empty flash reads do not mutate sessions', flash.includes('session.flashMessages.length === 0') && flash.includes('delete session.flashMessages'));
check('anonymous read-only marketing pages use lazy CSRF', csrf.includes('READ_ONLY_PUBLIC_PATHS') && csrf.includes('shouldIssueToken(req) ? ensureToken(req)'));
check('CSRF cookie is not rewritten when unchanged', csrf.includes("req.cookies?.['XSRF-TOKEN'] !== token"));
check('anonymous marketing HTML has shared stale-while-revalidate caching', publicPerf.includes('s-maxage=60') && app.includes('app.use(publicPerformance)'));
check('derived home bootstrap is cached with SWR', catalog.includes('homeBootstrapCache') && catalog.includes('homeViewCacheStaleMs') && catalog.includes('refreshHomeBootstrap'));
check('web server stays free of background read-model maintenance', !read('src/server.js').includes('prewarmHome'));
check('below-fold marketing rendering uses content-visibility', css.includes('content-visibility:auto') && css.includes('contain-intrinsic-size'));
check('phone bottom navigation has increased rounded corners', css.includes('border-radius:34px!important') && css.includes('border-radius:19px!important'));
check('large dashboard workspace no longer blocks first paint', workspace.includes(`dashboard-shell.js?v=${pkg.version}`) && workspace.includes('data-start="paint"') && workspace.includes(`data-modules="/js/dashboard-workspace.js?v=${pkg.version}`));
console.log(`v1.6.11 speed/end-to-end checks passed (${passed}/${passed}).`);
